def _items(d):
    out = []
    for lab, block in d.items():
        for line in block.strip().splitlines():
            t = line.strip()
            if t:
                out.append({"text": t, "label": lab, "lang": "ko"})
    return out


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    data = os.path.join(here, "data")
    os.makedirs(data, exist_ok=True)
    tr, fe = _items(TRAIN), _items(FRESH2)

    # 중복 검사: 학습·fresh2 서로, 그리고 기존 평가셋과 겹치면 안 된다(평가 오염 방지)
    seen = {}
    for name, items in (("train", tr), ("fresh2", fe)):
        for it in items:
            seen.setdefault(it["text"], []).append(name)
    dup = {t: v for t, v in seen.items() if len(v) > 1}
    old = set()
    for fn in ("text_eval_set.json", "text_eval_heldout.json", "text_eval_fresh.json"):
        p = os.path.join(data, fn)
        if os.path.exists(p):
            old |= {i["text"] for i in json.load(open(p, encoding="utf-8"))["items"]}
    clash = [t for t in seen if t in old]
    if dup or clash:
        print("중복 문장 있음 — 수정 필요:", dup, clash)
        sys.exit(1)

    note_tr = "텍스트 헤드(train_text_head.py) 학습용. 작성자 Claude 초안, 라벨 모호하면 직접 수정."
    note_fe = ("봉인 평가셋(fresh2): 학습·하이퍼파라미터·가중치 선택에 절대 쓰지 않는다. 최종 보고용. "
               "작성자 Claude 초안, 라벨 모호하면 직접 수정.")
    json.dump({"_note": note_tr, "items": tr}, open(os.path.join(data, "text_train_ko.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)
    json.dump({"_note": note_fe, "items": fe}, open(os.path.join(data, "text_eval_fresh2.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)
    from collections import Counter
    print("train", len(tr), dict(Counter(i["label"] for i in tr)))
    print("fresh2", len(fe), dict(Counter(i["label"] for i in fe)))


if __name__ == "__main__":
    main()
